package presentation

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"

	"github.com/kevinhorst/smine/internal/fsx"
	"github.com/kevinhorst/smine/internal/redact"
	"github.com/kevinhorst/smine/internal/trash"
)

const styleWithheldStub = "<!-- generated by /smine-style — a mining re-run rewrites this file; edit freely until then (Profile page or any editor) -->\n\n" +
	"No style profile is active: the last mining run produced a profile that matched the secret/PII check, so it was withheld. The next /smine-style run retries.\n"

func DefaultStylePath() string {
	home, err := os.UserHomeDir()
	if err != nil {
		return ""
	}
	return filepath.Join(home, ".claude", "context", "global", "style-profile.md")
}

// GuardStyleProfile keeps the profile in the trash and overwrites it with the withheld stub on any secret or PII hit.
func GuardStyleProfile(path string, store *trash.Store) ([]redact.Hit, error) {
	content, err := os.ReadFile(path)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("GuardStyleProfile: %w", err)
	}

	hits := redact.Scan(string(content))
	if len(hits) == 0 {
		return nil, nil
	}
	entry := &trash.Entry{Action: "style guard", Reason: "secret or PII hit, profile withheld"}
	if _, err := store.Keep(path, entry); err != nil {
		return hits, fmt.Errorf("GuardStyleProfile: %w", err)
	}
	if err := fsx.WriteFileAtomic([]byte(styleWithheldStub), path, 0o644); err != nil {
		return hits, fmt.Errorf("GuardStyleProfile: %w", err)
	}
	return hits, nil
}
