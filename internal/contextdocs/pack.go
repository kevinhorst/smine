package contextdocs

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/kevinhorst/smine/internal/fsx"
	"github.com/kevinhorst/smine/internal/reach"
	"github.com/kevinhorst/smine/internal/trash"
)

const alwaysPackHeader = "<!-- generated by rules pack from smine context (reach: always) — do not edit -->"

// actionContextSync names the context deploys in the trash journal.
const actionContextSync = "context sync"

func AlwaysPackFile() (string, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return "", fmt.Errorf("AlwaysPackFile: %w", err)
	}

	return filepath.Join(home, ".claude", "context", "global", "always-context.md"), nil
}

// The inverse boundary of FilterRulesFile: always entries ship only to the always pack.
func PackAlwaysEntries(content string) string {
	lines := strings.Split(content, "\n")
	var blocks []string
	isInFence := false
	isInTombstones := false

	for index := 0; index < len(lines); index++ {
		line := lines[index]
		if strings.HasPrefix(line, "```") {
			isInFence = !isInFence
			continue
		}
		if isInFence {
			continue
		}
		if strings.HasPrefix(line, "## ") {
			isInTombstones = strings.TrimSpace(line) == "## Tombstones"
			continue
		}
		if isInTombstones {
			continue
		}

		match := ruleEntryPattern.FindStringSubmatch(line)
		if match == nil {
			continue
		}

		blockEnd := entryContentEnd(lines, index)
		if entryBlockReach(lines[index:blockEnd]) == reach.Always {
			block := strings.TrimRight(strings.Join(lines[index:blockEnd], "\n"), "\n")
			blocks = append(blocks, block)
		}
		index = blockEnd - 1
	}
	return strings.Join(blocks, "\n\n")
}

func PackAlwaysDir(dir string) (string, error) {
	var files []string
	for _, sub := range []string{"actions", "facts", "rules"} {
		matches, err := filepath.Glob(filepath.Join(dir, sub, "*.md"))
		if err != nil {
			return "", fmt.Errorf("PackAlwaysDir: %w", err)
		}
		files = append(files, matches...)
	}
	sort.Strings(files)

	var blocks []string
	for _, file := range files {
		content, err := os.ReadFile(file)
		if err != nil {
			return "", fmt.Errorf("PackAlwaysDir: %w", err)
		}
		if packed := PackAlwaysEntries(string(content)); packed != "" {
			blocks = append(blocks, packed)
		}
	}
	return strings.Join(blocks, "\n\n"), nil
}

// AlwaysPackContent is the file content for a packed body: the header, a blank line, the pack, a newline.
func AlwaysPackContent(packed string) string {
	return alwaysPackHeader + "\n\n" + packed + "\n"
}

// IsAlwaysPack reports a file that starts with the pack header: the one the engine may remove or rewrite (master C12).
func IsAlwaysPack(path string) (bool, error) {
	data, err := os.ReadFile(path)
	if errors.Is(err, fs.ErrNotExist) {
		return false, nil
	}
	if err != nil {
		return false, fmt.Errorf("IsAlwaysPack: %w", err)
	}
	return strings.HasPrefix(string(data), alwaysPackHeader), nil
}

// RemoveAlwaysPack moves the pack into the trash; a file without the header is kept with an error naming it.
func RemoveAlwaysPack(packFile string, keep *trash.Store) error {
	isPack, err := IsAlwaysPack(packFile)
	if err != nil {
		return fmt.Errorf("RemoveAlwaysPack: %w", err)
	}
	if !isPack {
		return fmt.Errorf("RemoveAlwaysPack: %s kept: no smine header", packFile)
	}
	entry := &trash.Entry{Action: actionContextSync, Reason: "always pack removed"}
	if _, err := keep.Move(packFile, entry); err != nil {
		return fmt.Errorf("RemoveAlwaysPack: %w", err)
	}
	return nil
}

// WriteAlwaysPack keeps the previous pack in the trash and writes the new one atomically; an empty pack removes a pack-headed file (master C12).
func WriteAlwaysPack(dir string, packFile string, keep *trash.Store) (bool, error) {
	packed, err := PackAlwaysDir(dir)
	if err != nil {
		return false, err
	}

	isPack, err := IsAlwaysPack(packFile)
	if err != nil {
		return false, fmt.Errorf("WriteAlwaysPack: %w", err)
	}
	if packed == "" {
		if !isPack {
			return false, nil
		}
		if err := RemoveAlwaysPack(packFile, keep); err != nil {
			return false, fmt.Errorf("WriteAlwaysPack: %w", err)
		}
		return false, nil
	}

	current, readErr := os.ReadFile(packFile)
	isPresent := readErr == nil
	if isPresent && !isPack {
		return false, fmt.Errorf("WriteAlwaysPack: %s kept: no smine header", packFile)
	}
	content := AlwaysPackContent(packed)
	if isPresent && string(current) == content {
		return false, nil
	}
	entry := &trash.Entry{Action: actionContextSync, Reason: "always pack rewritten"}
	if _, err := keep.Keep(packFile, entry); err != nil {
		return false, fmt.Errorf("WriteAlwaysPack: %w", err)
	}
	if err := fsx.WriteFileAtomic([]byte(content), packFile, 0o644); err != nil {
		return false, fmt.Errorf("WriteAlwaysPack: %w", err)
	}
	return true, nil
}
