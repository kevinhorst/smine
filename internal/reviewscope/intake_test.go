func TestIntake(t *testing.T) {
	fixture := newGitFixture(t)
	fixture.branch("claude/intake", "main")
	fixture.run("checkout", "-q", "claude/intake")
	writeIntakeFixture(t, fixture.repo, "internal/api/handler.go", "package api\n\nfunc Handle() {}\n")
	writeIntakeFixture(t, fixture.repo, "internal/api/handler_test.go", "package api\n\nimport \"testing\"\n\nfunc TestHandle(t *testing.T) {}\n")
	writeIntakeFixture(t, fixture.repo, "internal/api/types.pb.go", "package api\n")
	writeIntakeFixture(t, fixture.repo, "internal/api/marked.go", "// Code generated by foo. DO NOT EDIT.\npackage api\n")
	writeIntakeFixture(t, fixture.repo, "go.sum", "example.com/x v1.0.0 h1:abc\n")
	writeIntakeFixture(t, fixture.repo, "vendor/x/x.go", "package x\n")
	writeIntakeFixture(t, fixture.repo, "vendor/y/y.go", "package y\n")
	writeIntakeFixture(t, fixture.repo, "docs/guide.md", "# Guide\n\ntext\n")
	writeIntakeFixture(t, fixture.repo, "sessions/2026/a.jsonl", "{}\n{}\n")
	fixture.run("add", "-A")
	fixture.run("commit", "-q", "-m", "intake")
	head := fixture.run("rev-parse", "HEAD")
	base := fixture.run("rev-parse", "main")

	request := &IntakeRequest{Base: base, Head: head, Model: "opus", Repo: fixture.repo}
	report, err := Intake(context.Background(), request)
	require.NoError(t, err)

	expected := []Exclusion{
		{Class: classProse, Default: defaultKept, Files: 1, Lines: 3, Pathspec: "docs/"},
		{Class: classLockfile, Default: defaultExcluded, Files: 1, Lines: 1, Pathspec: "go.sum"},
		{Class: classGenerated, Default: defaultExcluded, Files: 1, Lines: 2, Pathspec: "internal/api/marked.go"},
		{Class: classGenerated, Default: defaultExcluded, Files: 1, Lines: 1, Pathspec: "internal/api/types.pb.go"},
		{Class: classRecords, Default: defaultKept, Files: 1, Lines: 2, Pathspec: "sessions/"},
		{Class: classVendored, Default: defaultExcluded, Files: 2, Lines: 2, Pathspec: "vendor/"},
	}
	assert.Equal(t, expected, report.Exclusions)
	assert.Equal(t, " exclude: go.sum internal/api/marked.go internal/api/types.pb.go vendor/ lanes: 2[opus:medium] station: opus:high", report.Suggested())
	assert.Len(t, report.Files, 9)

	reviewedFiles, reviewedLines := report.reviewedTotals()
	assert.Equal(t, 4, reviewedFiles)
	assert.Equal(t, 13, reviewedLines)
}

func TestIntake_Binary(t *testing.T) {
	fixture := newGitFixture(t)
	fixture.branch("claude/binary", "main")
	fixture.run("checkout", "-q", "claude/binary")
	require.NoError(t, os.MkdirAll(filepath.Join(fixture.repo, "assets"), 0o755))
	require.NoError(t, os.WriteFile(filepath.Join(fixture.repo, "assets", "logo.png"), []byte{0x89, 0x00, 0x00, 0x50}, 0o644))
	fixture.run("add", "-A")
	fixture.run("commit", "-q", "-m", "binary")
	head := fixture.run("rev-parse", "HEAD")
	base := fixture.run("rev-parse", "main")

	request := &IntakeRequest{Base: base, Head: head, Model: "opus", Repo: fixture.repo}
	report, err := Intake(context.Background(), request)
	require.NoError(t, err)

	expected := []Exclusion{{Class: classBinary, Default: defaultExcluded, Files: 1, Lines: 0, Pathspec: "assets/"}}
	assert.Equal(t, expected, report.Exclusions)
	assert.True(t, report.Files[0].IsBinary)
}

