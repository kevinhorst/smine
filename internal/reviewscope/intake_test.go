func TestIntake_RemovedAndRenamed(t *testing.T) {
	fixture := newGitFixture(t)
	writeIntakeFixture(t, fixture.repo, "internal/api/old.go", "package api\n\nfunc Old() {}\n")
	fixture.run("add", "-A")
	fixture.run("commit", "-q", "-m", "old")
	base := fixture.run("rev-parse", "main")
	fixture.branch("claude/removed", "main")
	fixture.run("checkout", "-q", "claude/removed")
	fixture.run("rm", "-q", "base")
	fixture.run("mv", "internal/api/old.go", "internal/api/new.go")
	fixture.run("commit", "-q", "-m", "removed")
	head := fixture.run("rev-parse", "HEAD")

	request := &IntakeRequest{Base: base, Head: head, Model: "opus", Repo: fixture.repo}
	report, err := Intake(context.Background(), request)
	require.NoError(t, err)

	expected := []ChangedFile{
		{Deleted: 1, IsRemoved: true, Path: "base"},
		{Added: 3, Path: "internal/api/new.go"},
		{Deleted: 3, IsRemoved: true, Path: "internal/api/old.go"},
	}
	assert.Equal(t, expected, report.Files)
	assert.Empty(t, report.Exclusions)
}

func TestIntakeReport_chunkSuggestion(t *testing.T) {
	type testCase struct {
		_id       string
		_expected string

		files int
		lines int
	}

	tests := make([]*testCase, 0)

	// within-bounds
	tests = append(tests, &testCase{
		_id:       "within-bounds",
		_expected: "",

		files: 50,
		lines: 4000,
	})

	// files-over
	tests = append(tests, &testCase{
		_id:       "files-over",
		_expected: "layers[40:667]",

		files: 120,
		lines: 2000,
	})

	// lines-over
	tests = append(tests, &testCase{
		_id:       "lines-over",
		_expected: "layers[4:3000]",

		files: 10,
		lines: 9000,
	})

	// both-over-lines-win
	tests = append(tests, &testCase{
		_id:       "both-over-lines-win",
		_expected: "layers[17:3334]",

		files: 51,
		lines: 10000,
	})

	// Run tests
	for _, test := range tests {
		t.Run(test._id, func(t *testing.T) {
			report := &IntakeReport{Files: provideReviewableFiles(test.files, test.lines)}
			assert.Equal(t, test._expected, report.chunkSuggestion())
		})
	}
}

func TestIntakeReport_Render(t *testing.T) {
	type testCase struct {
		_id       string
		_expected string

		isGate bool
		report *IntakeReport
	}

	tests := make([]*testCase, 0)

	// plain
	plain := &IntakeReport{Base: "b", Head: "h", Model: "opus", Files: provideReviewableFiles(2, 30)}
	tests = append(tests, &testCase{
		_id: "plain",
		_expected: "Diff: b..h — 2 files, 30 lines changed (30 added, 0 deleted)\n\nExclusions: none\n\nReviewed after exclusions: 2 files, 30 lines\n" +
			"Chunks: none needed (within 50 files / 4000 lines)\n" +
			"Models: lanes 2[opus:medium], station opus:high — strongest admitted subagent model; weaker classes are tested unviable (skill Model section)\n\n" +
			"Suggested: /railroad-review lanes: 2[opus:medium] station: opus:high\n",

		isGate: false,
		report: plain,
	})

	// gate-no-model
	noModel := &IntakeReport{Base: "b", Head: "h", Files: provideReviewableFiles(1, 1)}
	tests = append(tests, &testCase{
		_id: "gate-no-model",
		_expected: "Diff: b..h — 1 files, 1 lines changed (1 added, 0 deleted)\n\nExclusions: none\n\nReviewed after exclusions: 1 files, 1 lines\n" +
			"Chunks: none needed (within 50 files / 4000 lines)\n" +
			"Models: no subagent model admitted — see the skill's Model section\n\n" +
			"Suggested: /railroad-review\n\nReply go (the suggested line), defaults (no args), or /railroad-review <args>.\n",

		isGate: true,
		report: noModel,
	})

	// Run tests
	for _, test := range tests {
		t.Run(test._id, func(t *testing.T) {
			assert.Equal(t, test._expected, test.report.Render(test.isGate))
		})
	}
}

func TestParseNumstat(t *testing.T) {
	type testCase struct {
		_id         string
		_expected   []ChangedFile
		_shouldPass bool

		numstat string
	}

	tests := make([]*testCase, 0)

	// rows
	tests = append(tests, &testCase{
		_id:         "rows",
		_expected:   []ChangedFile{{Added: 3, Deleted: 1, Path: "a.go"}, {IsBinary: true, Path: "b.png"}},
		_shouldPass: true,

		numstat: "3\t1\ta.go\n-\t-\tb.png\n",
	})

	// empty
	tests = append(tests, &testCase{
		_id:         "empty",
		_expected:   []ChangedFile{},
		_shouldPass: true,

		numstat: "\n",
	})

	// malformed
	tests = append(tests, &testCase{
		_id:         "malformed",
		_expected:   nil,
		_shouldPass: false,

		numstat: "x\ty\n",
	})

	// Run tests
	for _, test := range tests {
		t.Run(test._id, func(t *testing.T) {
			files, err := parseNumstat(test.numstat)
			assert.Equalf(t, test._shouldPass, err == nil, "err = %v", err)
			assert.Equal(t, test._expected, files)
		})
	}
}

// provideReviewableFiles builds count reviewable files whose added lines sum to lines.
func provideReviewableFiles(count int, lines int) []ChangedFile {
	files := make([]ChangedFile, 0, count)
	for index := range count {
		added := lines / count
		if index == 0 {
			added += lines % count
		}
		files = append(files, ChangedFile{Added: added, Path: "file" + string(rune('a'+index%26)) + ".go"})
	}
	return files
}

// writeIntakeFixture writes one file of the intake fixture, creating its directory.
func writeIntakeFixture(t *testing.T, repo string, relative string, content string) {
	t.Helper()
	target := filepath.Join(repo, filepath.FromSlash(relative))
	require.NoError(t, os.MkdirAll(filepath.Dir(target), 0o755))
	require.NoError(t, os.WriteFile(target, []byte(content), 0o644))
}
