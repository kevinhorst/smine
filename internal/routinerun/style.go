package routinerun

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"path/filepath"

	"github.com/kevinhorst/smine/internal/fsx"
	"github.com/kevinhorst/smine/internal/presentation"
	"github.com/kevinhorst/smine/internal/trash"
)

const (
	styleProfileFile   = "style-profile.md"
	styleProfileMarker = "<!-- generated by /smine-style"
	styleStagingDir    = ".smine-run"
)

var ErrNotStyleProfile = errors.New("not a /smine-style profile")

// PublishStyleProfile is operator code only, so injected context is never agent-written; the previous profile goes to the trash.
func PublishStyleProfile(staged string, store *trash.Store) error {
	data, err := os.ReadFile(staged)
	if err != nil {
		return fmt.Errorf("PublishStyleProfile: %w", err)
	}

	if !bytes.HasPrefix(data, []byte(styleProfileMarker)) {
		return fmt.Errorf("PublishStyleProfile: %s: %w", staged, ErrNotStyleProfile)
	}

	entry := &trash.Entry{Action: "style publish", Reason: "mined profile published over the previous one"}
	if _, err := store.Keep(presentation.DefaultStylePath(), entry); err != nil {
		return fmt.Errorf("PublishStyleProfile: %w", err)
	}

	if err := fsx.WriteFileAtomic(data, presentation.DefaultStylePath(), 0o644); err != nil {
		return fmt.Errorf("PublishStyleProfile: %w", err)
	}
	return nil
}

// StyleStagingPath is where /smine-style writes its profile inside a checkout.
func StyleStagingPath(checkout string) string {
	return filepath.Join(checkout, styleStagingDir, styleProfileFile)
}
